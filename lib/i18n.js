export function normalizeUiLocale(value) {
  const locale = normalizeSttLanguage(value);
  return locale === STT_LANGUAGE_AUTO || !TRANSLATIONS[locale] ? "en" : locale;
}

export function uiMessages(value) {
  return TRANSLATIONS[normalizeUiLocale(value)];
}

export function translate(value, key, variables = {}) {
  const message = uiMessages(value)[key] || ENGLISH[key] || key;
  return message.replace(/\{(\w+)\}/g, (_, name) => String(variables[name] ?? `{${name}}`));
}

export function translationCoverage(value) {
  const messages = uiMessages(value);
  return KEYS.every((key) => typeof messages[key] === "string" && messages[key].length > 0);
}
