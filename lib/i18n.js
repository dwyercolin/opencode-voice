const KEYS = Object.freeze(Object.keys(ENGLISH));

// Values follow KEYS in order. Keeping each pack complete prevents a newly
// added setup string from silently falling back to English in one locale.
function pack(values) {
  if (values.length !== KEYS.length) {
    throw new Error(`Translation pack has ${values.length} values; expected ${KEYS.length}`);
  }
  return Object.freeze(Object.fromEntries(KEYS.map((key, index) => [key, values[index]])));
}

